# 出行日「主地点 vs 餐厅」的零用钱门槛（2026-11-10 用户口径，**取代** 270/500 双阈值）。
#
#   零用钱 ≥ GATE（360） → 去主地点（扭蛋流=步行街、小游戏流=游戏厅）
#   零用钱 <  GATE        → 去餐厅打工
#   零用钱读不到          → 主地点（不拿打工赌今天的消费）
