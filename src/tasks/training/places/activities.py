"""公园 / 餐厅 / 游戏厅 / 商店 的「前往XXX」按钮正则。

2026-11-01：原来 `ACTIVITY_GO` 是一个正则塞了 9 个地点名
（划船|野餐|散步|当服务员|桌游GM|游戏厅|商店|步行街|餐厅），
住在通用层里 —— 新增地点就得改通用层，而且「前往游戏厅」「前往步行街」
这种从没见过的组合也会被匹配。

现在每个地点模块给自己的正则，通用层只负责「按正则找」。
"""

import re

# 公园：散步 / 野餐 / 划船（三个都是公园内的活动）
PARK_GO = re.compile(r"^前往(划船|野餐|散步)")

# 餐厅：当服务员 / 桌游GM
RESTAURANT_GO = re.compile(r"^前往(当服务员|桌游GM)")

# 游戏厅 / 商店 / 步行街：直接进地点
ARCADE_GO = re.compile(r"^前往游戏厅")
SHOP_GO = re.compile(r"^前往商店")
STREET_GO = re.compile(r"^前往步行街")
